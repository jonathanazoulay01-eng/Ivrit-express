// Applique le genre choisi ("m" ou "f") à tout le programme.
// Chaque mot garde l'autre forme en 4e position pour l'afficher sur les cartes.
function applyGender(g) {
  const sIndex = {};
  GENDER_SENTENCES.forEach((p) => { sIndex[p[0]] = p; sIndex[p[1]] = p; });
  UNITS.forEach((u) => {
    if (!u._words) { u._words = u.words.map((w) => w.slice()); u._sentences = u.sentences.map((s) => s.slice()); }
    u.words = u._words.map((w) => {
      const f = GENDER_WORDS[w[0]];
      if (!f) return w.slice(0, 3);
      return g === "f" ? [f[0], f[1], f[2], w[0], "garçon"] : [w[0], w[1], w[2], f[0], "fille"];
    });
    u.sentences = u._sentences.map((s) => {
      const p = sIndex[s[0]];
      if (!p) return s.slice();
      const fr = s[1].replace(/ \((fille|garçon)\)$/, "");
      return g === "f" ? [p[1], p[3] || fr] : [p[0], p[2] || fr];
    });
  });
}
